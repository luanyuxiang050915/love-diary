    return {
        "id": f.id,
        "date": f.date.isoformat() if f.date else "",
        "level": f.level,
        "emoji": content.get("emoji", ""),
        "wish": content.get("wish", ""),
        "health": content.get("health", ""),
        "love": content.get("love", ""),
        "study": content.get("study", ""),
        "hint": content.get("hint", ""),
        "quote": content.get("quote", ""),
    }


