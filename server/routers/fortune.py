@router.post("/fortunes/draw")
def draw_fortune(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """抽签：当天已抽过则直接返回当天的签，否则随机抽一根并落库。"""
    today = date_cls.today()
    f = (
        db.query(Fortune)
        .filter(Fortune.user_id == current_user.id, Fortune.date == today)
        .first()
    )
    if f:
        return _to_out(f)

    picked = dict(random.choice(FORTUNES))
    picked["quote"] = random.choice(QUOTES[picked["level"]])
    f = Fortune(
        user_id=current_user.id,
        date=today,
        level=picked["level"],
        content=json.dumps(picked, ensure_ascii=False),
    )
    db.add(f)
    try:
        db.commit()
    except IntegrityError:
        # 并发抽签时唯一约束兜底：回滚后返回已存在的那条
        db.rollback()
        f = (
            db.query(Fortune)
            .filter(Fortune.user_id == current_user.id, Fortune.date == today)
            .first()
        )
        return _to_out(f)
    db.refresh(f)
    return _to_out(f)
